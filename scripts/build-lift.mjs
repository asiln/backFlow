// Builds plugin-lift/code.js: the merged "Backflow" plugin. The three engines (plugin/, plugin-tokens/,
// plugin-components/) are copied unchanged except for three mechanical rewrites, each in its own function
// scope so their top-level names cannot collide:
//   figma.showUI(__html__, ...)   removed (the host opens one window)
//   figma.ui.postMessage(          -> LIFT_UI.postMessage(   (tagged { mod, m } on the way out)
//   figma.ui.onmessage =           -> LIFT_UI.onmessage =    (the host routes { mod, m } back in)
// Run: node scripts/build-lift.mjs          (writes plugin-lift/code.js)
//      node scripts/build-lift.mjs --check  (exit 1 when code.js is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ENGINES = [['import', 'plugin/code.js'], ['tokens', 'plugin-tokens/code.js'], ['components', 'plugin-components/code.js']];

function rewrite(id, src) {
  const show = /^[ \t]*figma\.showUI\(__html__[^\n]*\);[ \t]*\r?\n/m;
  if (!show.test(src)) throw new Error(id + ': figma.showUI(__html__, ...) line not found');
  let out = src.replace(show, '');
  const on = out.match(/figma\.ui\.onmessage\s*=/g) || [];
  if (on.length !== 1) throw new Error(id + ': expected exactly one figma.ui.onmessage assignment, found ' + on.length);
  out = out.replace(/figma\.ui\.onmessage\s*=/, 'LIFT_UI.onmessage =').replace(/figma\.ui\.postMessage\(/g, 'LIFT_UI.postMessage(');
  const left = out.match(/figma\.ui\.\w+/g);
  if (left) throw new Error(id + ': unhandled figma.ui use: ' + [...new Set(left)].join(', '));
  if (out.includes('__html__')) throw new Error(id + ': stray __html__');
  return out;
}

export function buildLift() {
  const host = fs.readFileSync(path.join(root, 'plugin-lift/host.js'), 'utf8');
  if (!host.includes('/* @@ENGINES@@ */')) throw new Error('plugin-lift/host.js: @@ENGINES@@ marker missing');
  const parts = ['const LIFT_HANDLERS = {};',
    'function liftUi(mod) { return { postMessage: (m) => { try { figma.ui.postMessage({ mod, m }); } catch (e) { /* UI closed */ } }, set onmessage(fn) { LIFT_HANDLERS[mod] = fn; } }; }'];
  for (const [id, file] of ENGINES) {
    const src = fs.readFileSync(path.join(root, file), 'utf8');
    parts.push('// ===== engine "' + id + '" from ' + file + ' =====\n(function () {\nconst LIFT_UI = liftUi(' + JSON.stringify(id) + ');\n' + rewrite(id, src) + '\n})();');
  }
  const banner = '// GENERATED by scripts/build-lift.mjs from plugin-lift/host.js and ' + ENGINES.map((e) => e[1]).join(', ') + '. Do not edit; edit the sources and rebuild.\n';
  return banner + host.replace('/* @@ENGINES@@ */', () => parts.join('\n\n'));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = path.join(root, 'plugin-lift/code.js');
  const code = buildLift().replace(/\r\n/g, '\n');
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== code) { console.error('plugin-lift/code.js is stale: run node scripts/build-lift.mjs'); process.exit(1); }
    console.log('plugin-lift/code.js is up to date');
  } else {
    fs.writeFileSync(target, code);
    console.log('wrote plugin-lift/code.js (' + Math.round(code.length / 1024) + ' KB)');
  }
}
